package com.bokrilog.identity;

/**
 * 접근의 종류.
 *
 * <p>삭제 진행 중인 계정에서 무엇이 허용되고 무엇이 막히는지를 가르는 유일한 축이다. 삭제가
 * 시작되면 사용자는 자기 데이터를 계속 볼 수는 있어야 하지만 새 쓰기와 민감 작업은 즉시 막혀야
 * 한다(ERD {@code G-5}).
 */
public enum AccountAccessKind {

    /** 조회. 삭제 진행 중에도 허용한다. */
    READ,

    /** 일반 쓰기. 삭제가 시작되면 막힌다. */
    WRITE,

    /** 민감 작업. 로그인 수단 연결·해제, 자격정보 변경처럼 재인증이 필요한 종류다. */
    SENSITIVE
}
