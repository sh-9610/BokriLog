package com.bokrilog.identity;

/**
 * 삭제 경로의 결과.
 *
 * <p>부분 실패를 삭제 완료로 보고하지 않는다. 저장이 실패하면 이 타입의 값이 아니라 예외가
 * 나가고 트랜잭션은 통째로 롤백되며 계정 상태는 요청 전 그대로 남는다. 즉 {@link #COMPLETED}는
 * "요청한 지점까지 실제로 전진했다"만을 뜻한다.
 */
public enum DeletionOutcome {

    /**
     * 요청한 지점까지 상태가 전진했다. 이미 그 지점이거나 그 너머면 다시 요청해도 같은 값이다.
     * 삭제는 멱등하며 반복 요청이 상태를 되돌리지 않는다.
     */
    COMPLETED,

    /**
     * 전진하지 않았다. 상태는 요청 전과 같다.
     *
     * <p>대상 계정이 없거나, 삭제 전환을 거치지 않은 계정의 payload 삭제를 요청한 경우다.
     * 어느 쪽인지는 이 값에서 구분되지 않는다.
     */
    NOT_APPLICABLE
}
